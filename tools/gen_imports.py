#!/usr/bin/env python3
"""Generate src/injector/imports.h: name, library and NID of every hooked import (in the
DI_HOOK_LIST order of src/hook/dihook.h) plus the libkernel helpers the blob calls.
NID = base64(first 8 bytes of SHA1(name || suffix), read little endian), '/' -> '-'."""
import base64, hashlib, pathlib, re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SUFFIX = bytes.fromhex("518D64A635DED8C1E6B039B1C3E55230")

def nid(name):
    v = int.from_bytes(hashlib.sha1(name.encode() + SUFFIX).digest()[:8], "little")
    return base64.b64encode(v.to_bytes(8, "big")).decode().rstrip("=").replace("/", "-")

# self-check against NIDs known from shipping homebrew
assert nid("sceUsbdGetDeviceList") == "8qB9Ar4P5nc"
assert nid("scePadReadState") == "YndgXqQVV7c"
assert nid("scePadRead") == "q1cHNfGycLI"
assert nid("sceKernelUsleep") == "1jfXLRVzisc"
assert nid("scePthreadCreate") == "6UgtwV+0zb4"

text = (ROOT / "src/hook/dihook.h").read_text()
block = re.search(r"#define DI_HOOK_LIST\(X\)(.*?)\n\n", text, re.S).group(1)
hooks = re.findall(r"X\((\w+)\)", block)

rows = []
for h in hooks:
    if h.startswith("Pad"):
        name, lib = "sce" + h, "libScePad"
    else:
        name, lib = "sceUsbd" + h, "libSceUsbd"
    rows.append((name, lib, nid(name)))

out = ["/* generated by tools/gen_imports.py - do not edit */", "#pragma once", "#include <stdint.h>",
       "typedef struct { const char *name; const char *lib; const char *nid; } di_import;",
       "static const di_import DI_IMPORTS[] = {"]
out += [f'    {{"{n}", "{l}", "{i}"}},' for n, l, i in rows]
out += ["};",
        f'static const di_import DI_USLEEP = {{"sceKernelUsleep", "libkernel", "{nid("sceKernelUsleep")}"}};',
        f'static const di_import DI_PTHREAD_CREATE = {{"scePthreadCreate", "libkernel", "{nid("scePthreadCreate")}"}};',
        ""]
(ROOT / "src/injector/imports.h").write_text("\n".join(out))
print(f"imports.h: {len(rows)} imports")
